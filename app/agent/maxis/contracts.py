"""Strict contracts crossing the LTM -> MAXIS/Dify trust boundary.

These models deliberately contain no approval token, executable Jira payload, provider
credential, or conversation state.  Semantic output remains a proposal until the existing
LTM deterministic validators and approval path accept it.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from datetime import date, datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


Identifier = Annotated[
    str,
    Field(min_length=1, max_length=128, pattern=r"^[A-Za-z0-9][A-Za-z0-9._:-]*$"),
]
ShortText = Annotated[str, Field(min_length=1, max_length=500)]
Digest = Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]
MAX_PAYLOAD_SCHEMA_CHARS = 4_096
MAX_PAYLOAD_SCHEMA_UTF8_BYTES = 4_096

# JSON Schema annotations help humans and local prompt authors, but they do not
# participate in instance validation.  Removing them from the MAXIS wire schema keeps
# the model-visible contract small without weakening the full local Role validator.
_SCHEMA_ANNOTATION_KEYS = frozenset({
    "$comment", "default", "deprecated", "description", "examples", "readOnly",
    "title", "writeOnly",
})
_SCHEMA_MAP_KEYWORDS = frozenset({
    "$defs", "definitions", "dependentSchemas", "patternProperties", "properties",
})
_SCHEMA_SINGLE_KEYWORDS = frozenset({
    "additionalItems", "additionalProperties", "contains", "contentSchema", "else",
    "if", "items", "not", "propertyNames", "then", "unevaluatedItems",
    "unevaluatedProperties",
})
_SCHEMA_ARRAY_KEYWORDS = frozenset({"allOf", "anyOf", "oneOf", "prefixItems"})


def _strict_json_object(value: str) -> dict[str, Any]:
    """Decode one finite JSON object without accepting duplicate member names."""

    def object_pairs(pairs):
        result: dict[str, Any] = {}
        for key, item in pairs:
            if key in result:
                raise ValueError("duplicate JSON object key")
            result[key] = item
        return result

    def invalid_constant(_value):
        raise ValueError("non-finite JSON number")

    decoded = json.loads(
        value,
        object_pairs_hook=object_pairs,
        parse_constant=invalid_constant,
    )
    if not isinstance(decoded, dict):
        raise TypeError("JSON object required")
    return decoded


def _validate_schema_shape(value: Any, *, depth: int = 0, counter: list[int] | None = None) -> None:
    """Bound a caller-supplied schema before handing it to ``jsonschema``.

    The schema is generated by LTM, but it still crosses an adapter boundary.  Local-only
    references prevent a crafted pack from turning response validation into external schema
    resolution, while depth/node/string limits keep pathological inputs cheap to reject.
    """

    if counter is None:
        counter = [0]
    counter[0] += 1
    if counter[0] > 1_024 or depth > 24:
        raise ValueError("payload schema exceeds structural limits")
    if value is None or isinstance(value, bool):
        return
    if isinstance(value, int):
        return
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError("payload schema contains a non-finite number")
        return
    if isinstance(value, str):
        if len(value) > 4_000:
            raise ValueError("payload schema string is too long")
        return
    if isinstance(value, list):
        if len(value) > 256:
            raise ValueError("payload schema collection is too large")
        for item in value:
            _validate_schema_shape(item, depth=depth + 1, counter=counter)
        return
    if isinstance(value, dict):
        if len(value) > 256:
            raise ValueError("payload schema object is too large")
        for key, item in value.items():
            if not isinstance(key, str) or not key or len(key) > 256:
                raise ValueError("payload schema key is invalid")
            if key in {"$ref", "$dynamicRef", "$recursiveRef"} and (
                not isinstance(item, str) or not item.startswith("#")
            ):
                raise ValueError("payload schema references must be local")
            _validate_schema_shape(item, depth=depth + 1, counter=counter)
        return
    raise TypeError("payload schema must contain JSON values only")


def _model_schema(value: Any) -> Any:
    """Drop only validation-neutral annotations from schema-bearing positions.

    Property and definition *names* are data, so a field literally named ``title`` or
    ``default`` must survive.  Recursion therefore follows JSON Schema applicator
    keywords instead of deleting matching keys from arbitrary objects such as ``const``.
    """

    if not isinstance(value, dict):
        return value
    projected: dict[str, Any] = {}
    for key, item in value.items():
        if key in _SCHEMA_ANNOTATION_KEYS:
            continue
        if key in _SCHEMA_MAP_KEYWORDS and isinstance(item, dict):
            projected[key] = {
                name: _model_schema(child) for name, child in item.items()
            }
        elif key in _SCHEMA_SINGLE_KEYWORDS and isinstance(item, dict):
            projected[key] = _model_schema(item)
        elif key in _SCHEMA_ARRAY_KEYWORDS and isinstance(item, list):
            projected[key] = [
                _model_schema(child) if isinstance(child, dict) else child
                for child in item
            ]
        else:
            projected[key] = item
    return projected


def canonical_payload_schema(value: Any) -> tuple[str, str]:
    """Return the bounded model-facing JSON Schema and its SHA-256 binding."""

    if isinstance(value, str):
        schema = _strict_json_object(value)
    elif isinstance(value, dict):
        # Bound first, then round-trip to detach every nested object from a mutable caller
        # before schema validation and digest calculation.
        _validate_schema_shape(value)
        try:
            snapshot = json.dumps(
                value,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            )
            schema = _strict_json_object(snapshot)
        except (TypeError, ValueError, RecursionError) as exc:
            raise TypeError("payload schema must contain JSON values only") from exc
    else:
        raise TypeError("payload schema must be a JSON object")
    _validate_schema_shape(schema)
    if schema.get("type") != "object":
        raise ValueError("payload schema root must have type=object")
    try:
        from jsonschema.validators import validator_for

        validator_type = validator_for(schema)
        validator_type.check_schema(schema)
    except Exception as exc:
        raise ValueError("payload schema is invalid") from exc
    model_schema = _model_schema(schema)
    encoded = json.dumps(
        model_schema,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    )
    if (
        len(encoded) > MAX_PAYLOAD_SCHEMA_CHARS
        or len(encoded.encode("utf-8")) > MAX_PAYLOAD_SCHEMA_UTF8_BYTES
    ):
        raise ValueError("payload schema is too large")
    return encoded, hashlib.sha256(encoded.encode("utf-8")).hexdigest()


class StrictFrozenModel(BaseModel):
    """A fail-closed wire model: no coercion, extension fields, or reassignment."""

    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)


def _aware(value: datetime, field: str) -> datetime:
    if value.tzinfo is None or value.utcoffset() is None:
        raise ValueError(f"{field} must include a timezone")
    return value


def _canonical_due_date(value: str) -> str:
    if not value:
        return value
    try:
        parsed = date.fromisoformat(value)
    except ValueError as exc:
        raise ValueError("duedate must use YYYY-MM-DD") from exc
    if parsed.isoformat() != value:
        raise ValueError("duedate must use YYYY-MM-DD")
    return value


