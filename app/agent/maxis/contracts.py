class RoleContextV1(StrictFrozenModel):
    """Bounded workflow state which is context, never citation-grade evidence."""

    context_id: Identifier
    name: Identifier
    content_json: Annotated[str, Field(min_length=1, max_length=4000)]
    observed_at: datetime
    content_sha256: Digest
    partial: bool = False

    @model_validator(mode="after")
    def validate_context(self):
        _aware(self.observed_at, "observed_at")
        try:
            value = json.loads(self.content_json)
            canonical = json.dumps(
                value,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            )
        except (TypeError, ValueError) as exc:
            raise ValueError("content_json must contain canonical JSON") from exc
        if canonical != self.content_json:
            raise ValueError("content_json must contain canonical JSON")
        actual = hashlib.sha256(self.content_json.encode("utf-8")).hexdigest()
        if actual != self.content_sha256:
            raise ValueError("content_sha256 does not match content_json")
        return self


class EvidencePackV1(StrictFrozenModel):
    contract: Literal["evidence-pack.v1"] = "evidence-pack.v1"
    request_id: Identifier
    use_case: Identifier
    query: Annotated[str, Field(min_length=1, max_length=4000)]
    pseudonymous_user: Annotated[
        str, Field(pattern=r"^ltm_[0-9a-f]{16}$")
    ]
    requested_at: datetime
    scope: EvidenceScopeV1
    sources: tuple[EvidenceSourceV1, ...] = Field(max_length=10)
    facts: tuple[EvidenceFactV1, ...] = Field(default=(), max_length=40)
    metrics: tuple[EvidenceMetricV1, ...] = Field(default=(), max_length=40)
    role_context: tuple[RoleContextV1, ...] = Field(default=(), max_length=8)
    freshness: Literal["fresh", "mixed", "stale", "empty"]
    partial: bool
    flags: tuple[Identifier, ...] = Field(default=(), max_length=16)
    knowledge_manifest_sha256: Digest | None = None
    payload_schema_json: Annotated[
        str, Field(min_length=2, max_length=MAX_PAYLOAD_SCHEMA_CHARS)
    ]
    payload_schema_sha256: Digest

    @model_validator(mode="after")
    def validate_pack(self):
        _aware(self.requested_at, "requested_at")
        source_ids = [row.source_id for row in self.sources]
        if len(source_ids) != len(set(source_ids)):
            raise ValueError("source ids must be unique")
        known = set(source_ids)
        for row in (*self.facts, *self.metrics):
            if not set(row.source_ids).issubset(known):
                raise ValueError("fact/metric references an unknown source")
        context_ids = [row.context_id for row in self.role_context]
        context_names = [row.name for row in self.role_context]
        if len(context_ids) != len(set(context_ids)):
            raise ValueError("role context ids must be unique")
        if len(context_names) != len(set(context_names)):
            raise ValueError("role context names must be unique")
        if len(self.flags) != len(set(self.flags)):
            raise ValueError("flags must be unique")
        observations = bool(self.sources or self.role_context)
        if not observations and self.freshness != "empty":
            raise ValueError("an empty evidence/context set must use freshness=empty")
        if observations and self.freshness == "empty":
            raise ValueError("a non-empty evidence/context set cannot use freshness=empty")
        canonical_schema, schema_digest = canonical_payload_schema(
            self.payload_schema_json
        )
        if canonical_schema != self.payload_schema_json:
            raise ValueError("payload_schema_json must contain canonical JSON")
        if schema_digest != self.payload_schema_sha256:
            raise ValueError("payload_schema_sha256 does not match payload_schema_json")
        return self

    def payload_schema(self) -> dict[str, Any]:
        """Return the already verified per-call schema as a fresh JSON object."""

        return _strict_json_object(self.payload_schema_json)


