class PayloadClaimBindingV1(StrictFrozenModel):
    """Bind one narrative payload field to the claims that support its value.

    ``path`` is a canonical JSON Pointer into ``RemoteRoleResultV1.payload``.  The
    response guard resolves the pointer against the received payload and verifies
    that the pointed-to text is actually present in the cited claim text.  Keeping
    this as an explicit wire contract prevents a workflow from returning a grounded
    side claim next to an unrelated headline or finding.
    """

    path: Annotated[str, Field(min_length=1, max_length=500)]
    claim_ids: tuple[Identifier, ...] = Field(min_length=1, max_length=40)

    @model_validator(mode="after")
    def validate_binding(self):
        if not self.path.startswith("/"):
            raise ValueError("payload claim path must be a JSON Pointer")
        segments = self.path[1:].split("/")
        if any(not segment or re.search(r"~(?![01])", segment) for segment in segments):
            raise ValueError("payload claim path must use canonical JSON Pointer escapes")
        if len(self.claim_ids) != len(set(self.claim_ids)):
            raise ValueError("payload claim ids must be unique")
        return self


class RemoteRoleResultV1(StrictFrozenModel):
    # correlation_id is intentionally absent. It is an input-only request/audit
    # binding checked against EvidencePackV1.request_id before dispatch; accepting it
    # here would contradict the closed remote response contract.
    contract: Literal["remote-role-result.v1"] = "remote-role-result.v1"
    role_id: Literal[
        "request_architect",
        "query_specialist",
        "knowledge_curator",
        "portfolio_analyst",
        "work_architect",
        "auditor",
        "result_integrator",
        "editor_author",
    ]
    status: Literal["ok", "needs_input", "blocked"]
    payload: dict[str, Any]
    claims: tuple[RemoteClaimV1, ...] = Field(default=(), max_length=40)
    payload_claims: tuple[PayloadClaimBindingV1, ...] = Field(default=(), max_length=256)
    citations: tuple[CitationV1, ...] = Field(default=(), max_length=40)
    missing_inputs: tuple[ShortText, ...] = Field(default=(), max_length=8)
    warnings: tuple[ShortText, ...] = Field(default=(), max_length=16)
    workflow_version: Annotated[str, Field(min_length=1, max_length=120)]
    knowledge_version: Annotated[str, Field(min_length=1, max_length=120)]
    knowledge_manifest_sha256: Digest
    # Populated from the Dify Knowledge Retrieval node on every remote Role call.
    # The activation canary compares its digest with the value pinned locally in the
    # selected profile.  The expected value is never sent to Dify.
    knowledge_proof: Annotated[str, Field(max_length=240)]

    @model_validator(mode="after")
    def validate_result(self):
        citation_ids = [row.citation_id for row in self.citations]
        if len(citation_ids) != len(set(citation_ids)):
            raise ValueError("citation ids must be unique")
        known = set(citation_ids)
        for claim in self.claims:
            if not set(claim.citation_ids).issubset(known):
                raise ValueError("claim references an unknown citation")
        raw_claim_ids = [row.claim_id for row in self.claims]
        if len(raw_claim_ids) != len(set(raw_claim_ids)):
            raise ValueError("claim ids must be unique")
        claim_ids = set(raw_claim_ids)
        paths = [row.path for row in self.payload_claims]
        if len(paths) != len(set(paths)):
            raise ValueError("payload claim paths must be unique")
        for binding in self.payload_claims:
            if not set(binding.claim_ids).issubset(claim_ids):
                raise ValueError("payload binding references an unknown claim")
        if self.status == "needs_input" and not self.missing_inputs:
            raise ValueError("needs_input requires at least one missing input")
        if self.status == "ok" and self.missing_inputs:
            raise ValueError("ok cannot contain missing inputs")
        if self.status != "ok" and self.payload:
            raise ValueError("non-ok results must keep payload empty")
        if self.status != "ok" and (
            self.claims or self.payload_claims or self.citations
        ):
            raise ValueError("non-ok results must keep provenance empty")
        return self


