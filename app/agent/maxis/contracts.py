class EvidenceSourceV1(StrictFrozenModel):
    source_id: Identifier
    kind: Literal["jira", "confluence", "bitbucket", "knowledge", "ltm"]
    canonical_id: Annotated[str, Field(min_length=1, max_length=240)]
    title: Annotated[str, Field(min_length=1, max_length=240)]
    scope: Annotated[str, Field(default="", max_length=160)] = ""
    url: Annotated[str, Field(default="", max_length=2048)] = ""
    content: Annotated[str, Field(max_length=1500)]
    retrieved_at: datetime
    updated_at: datetime | None = None
    content_sha256: Digest
    partial: bool = False
    truncated: bool = False

    @model_validator(mode="after")
    def validate_source(self):
        _aware(self.retrieved_at, "retrieved_at")
        if self.updated_at is not None:
            _aware(self.updated_at, "updated_at")
        actual = hashlib.sha256(self.content.encode("utf-8")).hexdigest()
        if actual != self.content_sha256:
            raise ValueError("content_sha256 does not match content")
        if self.kind in {"jira", "confluence", "bitbucket"} and not self.scope:
            raise ValueError(f"{self.kind} source requires an explicit scope")
        return self


